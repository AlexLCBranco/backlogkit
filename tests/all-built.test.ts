import { describe, expect, it } from 'vitest';
import { loadAll } from '../lib/github.mjs';
// @ts-expect-error plain JS script, no types
import { allBacklog, allBuilt } from '../scripts/all-built.mjs';
import { itemMarkdown } from '../lib/lists.mjs';
import { BACKLOG, BUILT, mockGithub, projectsJson } from './fixtures';

const load = (token?: string) =>
  loadAll({
    token,
    fetchImpl: mockGithub({
      repos: [{ name: 'demo' }, { name: 'zeta' }, { name: 'bare' }, { name: 'locked' }],
      files: {
        demo: { 'FEATURE_BACKLOG.md': BACKLOG, 'BUILT.md': BUILT },
        zeta: { 'BUILT.md': '## 2026-11-17\n- ZT-1 — Zeta thing (v0.2.0)\n', 'FEATURE_BACKLOG.md': '## Ready\n\n### ZT-2 – Next zeta\nDo it.\n' },
      },
      fails: { locked: 403 },
      projectsJson: projectsJson([{ repo: 'demo' }, { repo: 'private-one' }]),
    }).fetchImpl,
  });

describe('all-built generator (repos from GitHub + projects.json, shared parser)', () => {
  it('ALL_BUILT.md: newest day first, repos A–Z, detail joined, Internal left out, unread repos named', async () => {
    const md = allBuilt(await load('test-token-xyz'));
    expect(md).toBe(`# Built — all repos

Generated by \`scripts/all-built.mjs\` in backlogkit from each repo's \`BUILT.md\` (daily, and on demand from the Actions
tab). Do not edit by hand.
Newest day first; "### Internal" housekeeping left out.

Not read this run: locked (Not read: locked/FEATURE_BACKLOG.md: HTTP 403 (no access or rate limit)).

## 2026-11-17

**demo**
- DM-5 — Newest thing (v1.3.0) What the owner sees now.
- A fix without ID (v1.2.1)

**zeta**
- ZT-1 — Zeta thing (v0.2.0)

## 2026-11-16

**demo**
- v1.2.0: old style line

## 2026-11-15

**demo**
- DM-0 — Older thing (v1.1.0)
`);
    expect(md).not.toContain('secret housekeeping');
  });

  it('ALL_BACKLOG.md: every repo with planned items, sections and full item text', async () => {
    const md = allBacklog(await load('test-token-xyz'));
    expect(md).toContain('## demo\n\n### Ready\n\n#### DM-1 — First thing\nLine one of the spec.\n- a bullet\n  continued\n\n#### DM-2 — Stuck thing');
    expect(md).toContain('### Held (needs the owner\'s "go")\n\n#### DM-3 — Later thing\nHeld text.\n\n## zeta\n\n### Ready\n\n#### ZT-2');
    expect(md.indexOf('## demo')).toBeLessThan(md.indexOf('## zeta'));
    expect(md).not.toContain('## bare');
  });

  it('without a token, private repos from projects.json are listed as not read', async () => {
    const md = allBacklog(await load());
    expect(md).toMatch(/Not read this run: .*private-one \(Unread: not public on GitHub/);
  });

  it('itemMarkdown: heading line plus body; no body → heading only', () => {
    expect(itemMarkdown({ id: 'X-1', title: 'T', body: 'b' })).toBe('### X-1 — T\nb');
    expect(itemMarkdown({ id: null, title: 'T', body: '' }, 4)).toBe('#### T');
  });
});
