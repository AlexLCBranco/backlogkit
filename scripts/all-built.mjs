// Writes ALL_BUILT.md (every repo's BUILT.md merged: newest day first, then repo; "### Internal" left out) and
// ALL_BACKLOG.md (every repo's planned items, by repo). Moved here from gauntlet (BL-2). The repo list is GitHub's
// (every repo of the owner) merged with projects.json, read the same way and with the same parser as the site
// (lib/github.mjs, lib/lists.mjs). Runs daily from .github/workflows/all-built.yml, and on demand from the Actions tab.
// Token: env ALL_BUILT_TOKEN (fine-grained, Contents: read). Without it only public repos are read.
import { writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { loadAll } from '../lib/github.mjs'

const GENERATED = (what) => [
  `Generated by \`scripts/all-built.mjs\` in backlogkit from each repo's ${what} (daily, and on demand from the Actions`,
  'tab). Do not edit by hand.',
]

/** "Not read this run: …" for repos the loader could not read (none → no line). */
function notRead(projects) {
  const missing = projects.filter((p) => p.error).map((p) => `${p.repo} (${p.error})`)
  return missing.length ? [`Not read this run: ${missing.join(', ')}.`, ''] : []
}

/** ALL_BUILT.md's text: newest day first, repos A–Z within a day, items as written in each BUILT.md. */
export function allBuilt(data) {
  const byDay = new Map()
  for (const p of data.projects)
    for (const d of p.built) {
      if (!byDay.has(d.date)) byDay.set(d.date, [])
      byDay.get(d.date).push({ repo: p.repo, items: d.items })
    }
  const out = ['# Built — all repos', '', ...GENERATED('`BUILT.md`'), 'Newest day first; "### Internal" housekeeping left out.', '', ...notRead(data.projects)]
  for (const date of [...byDay.keys()].sort().reverse()) {
    out.push(`## ${date}`, '')
    for (const r of byDay.get(date).sort((a, b) => a.repo.localeCompare(b.repo)))
      out.push(`**${r.repo}**`, ...r.items.map((i) => `- ${i.detail ? `${i.text} ${i.detail}` : i.text}`), '')
  }
  return out.join('\n').trimEnd() + '\n'
}

/** One planned item as Markdown: its heading line and full spec text, as in the repo's FEATURE_BACKLOG.md. */
export function itemMarkdown(item, level = 3) {
  const heading = item.heading ?? (item.id ? `${item.id} — ${item.title}` : item.title)
  return `${'#'.repeat(level)} ${heading}${item.body ? `\n${item.body}` : ''}`
}

/** ALL_BACKLOG.md's text: repos A–Z (only those with planned items), each with its sections and items in file order. */
export function allBacklog(data) {
  const out = ['# Backlog — all repos', '', ...GENERATED('`FEATURE_BACKLOG.md`'), 'Planned items only, by repo.', '', ...notRead(data.projects)]
  const withPlans = data.projects.filter((p) => p.planned.some((s) => s.items.length)).sort((a, b) => a.repo.localeCompare(b.repo))
  if (!withPlans.length) out.push('Nothing planned anywhere.')
  for (const p of withPlans) {
    out.push(`## ${p.repo}`, '')
    for (const s of p.planned.filter((x) => x.items.length)) {
      out.push(`### ${s.name}`, '')
      for (const i of s.items) out.push(itemMarkdown(i, 4), '')
    }
  }
  return out.join('\n').trimEnd() + '\n'
}

async function main() {
  const data = await loadAll({ token: process.env.ALL_BUILT_TOKEN?.trim() || undefined })
  if (data.problems.length) {
    console.error(`all-built: ${data.problems.join('; ')}`)
    process.exit(1) // without the repo list or projects.json the files would silently lose repos: keep yesterday's
  }
  writeFileSync('ALL_BUILT.md', allBuilt(data))
  writeFileSync('ALL_BACKLOG.md', allBacklog(data))
  const read = data.projects.filter((p) => !p.error && !p.noFiles && p.github)
  const failed = data.projects.filter((p) => p.error).map((p) => p.repo)
  console.log(`all-built: ${read.length} repos read${failed.length ? `; not read: ${failed.join(', ')}` : ''}${data.tokenSet ? '' : ' (no token: public repos only)'}`)
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main()
